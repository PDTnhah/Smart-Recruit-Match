-- AD-4, FR-13, CONTEXT D39.
-- The AI Service reads the skill catalogue only through these views. v_ai_skills is the catalogue:
-- APPROVED skills, terminal in skillMachine. v_ai_skill_candidates holds the new names awaiting
-- ADMIN, for the suggestion job; a reviewed name leaves it. `version` is the row version, so an
-- embedding of an older version of a skill is ignored (ai.embeddings key).
CREATE OR REPLACE VIEW core.v_ai_skills WITH (security_barrier) AS
  SELECT id AS skill_id, canonical_name, aliases, "group", row_version AS version
  FROM core.skills
  WHERE status IN ('APPROVED');
