import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  AI_JOB_MAX_ATTEMPTS,
  AI_JOB_RETRY_DELAYS_SECONDS,
  AiResultMessageSchema,
  CvParseJobSchema,
  JdAnalyzeJobSchema,
  MATCH_RESULT_CHUNK_MAX,
  MatchRunJobSchema,
  SKILL_NORMALIZE_BATCH,
  SkillNormalizeJobSchema,
  aiQueueManifest,
  allAiQueues,
  buildContractSchemas,
} from '../index.js';

const repo = join(__dirname, '../../../..');
const jsonSchemaDir = join(repo, 'packages/shared/contracts/json-schema');
const pythonDir = join(repo, 'ai-service/app/contracts');
const HEADER = '# generated by `pnpm contracts:gen` from packages/shared/contracts - do not edit';

// Parsed, not compared as text: a Windows checkout may have CRLF line endings.
const readJson = (file: string): unknown => JSON.parse(readFileSync(file, 'utf8'));

const JOB_ID = '7f6c1e2a-4b8d-4c1e-9a2b-3c4d5e6f7a8b';
const cvJob = { job_id: JOB_ID, cv_id: 457, cv_version: 2, file_key: 'cvs/457/2.pdf' };
const profile = {
  summary: null,
  education: [],
  skills: [{ name: 'Java', canonical_name: 'Java', match: 'ALIAS' }],
  projects: [],
  experience: [],
  languages: [],
  certificates: [],
};
const output = {
  prompt_version: 'cv_parser/v1',
  model: 'gemini-3.8-flash',
  cv_id: 457,
  cv_version: 2,
  source: 'TEXT_PDF',
  profile,
  pii: {
    full_name: 'Nguyễn Văn Test',
    emails: [],
    phones: [],
    links: [],
    address: null,
    date_of_birth: null,
    gender: null,
    hometown: null,
    religion: null,
    marital_status: null,
    has_photo: false,
  },
  profile_masked: profile,
  new_skills: [],
  masked_text: '[NAME] Java',
  hidden_text_detected: false,
};
const succeeded = { job_id: JOB_ID, type: 'CV_PARSE', status: 'SUCCEEDED', job: cvJob, result: output, error: null };
const pair = { cv_id: 457, cv_version: 2, jd_id: 9, jd_version: 1 };
const matchJob = {
  job_id: JOB_ID,
  campaign_id: 3,
  rules_version: 'matching-rules/v1+language-cefr/v1+soft-skill-signals/v1',
  prompt_version: 'matching/v1',
  pairs: [pair],
};
const matchItem = {
  ...pair,
  model: 'gemini-3.8-flash',
  assessment: {
    project_relevance: { score_0_4: 3, reason: 'Dự án web Java', evidence: ['Quản lý thư viện'] },
    strengths: [],
    suggestions: [],
    summary: 'Phù hợp.',
  },
  evidence_check: [{ quote: 'Quản lý thư viện', score: 100, matched: true }],
};
const matchResult = {
  job_id: JOB_ID,
  type: 'MATCH',
  status: 'SUCCEEDED',
  job: matchJob,
  result: { prompt_version: 'matching/v1', final: false, items: [matchItem], failed_pairs: [] },
  error: null,
};
const failure = { code: 'RETRIES_EXHAUSTED', message: 'boom', needs_human: false };

describe('AD-6: contracts are generated, not written by hand', () => {
  const schemas = buildContractSchemas();
  const ids = Object.keys(schemas).sort();

  it('AD-6 mọi message có JSON Schema và model Pydantic sinh tự động', () => {
    const jsonFiles = readdirSync(jsonSchemaDir).filter((f) => f.endsWith('.json')).sort();
    expect(jsonFiles).toEqual(ids.map((id) => `${id}.json`));
    for (const id of ids) {
      expect(readJson(join(jsonSchemaDir, `${id}.json`))).toEqual(schemas[id]);
      const python = readFileSync(join(pythonDir, `${id}.py`), 'utf8');
      expect(python.startsWith(HEADER)).toBe(true);
    }
    const pythonFiles = readdirSync(pythonDir).filter((f) => f.endsWith('.py') && f !== '__init__.py').sort();
    expect(pythonFiles).toEqual(ids.map((id) => `${id}.py`));
  });

  it('AD-6 queue constants reach Python through queues.json', () => {
    expect(readJson(join(pythonDir, 'queues.json'))).toEqual(aiQueueManifest());
  });

  it('AD-6 every object schema forbids unknown fields', () => {
    for (const schema of Object.values(schemas)) {
      if (schema.type === 'object') expect(schema.additionalProperties).toBe(false);
    }
  });

  it('NFR-10 one retry delay between each of the 3 attempts', () => {
    expect(AI_JOB_MAX_ATTEMPTS).toBe(3);
    expect(AI_JOB_RETRY_DELAYS_SECONDS).toHaveLength(AI_JOB_MAX_ATTEMPTS - 1);
  });

  it('NFR-10 every job queue and the results queue has a DLQ', () => {
    expect(allAiQueues()).toEqual([
      'ai.cv.parse',
      'ai.jd.analyze',
      'ai.skills.normalize',
      'ai.match.run',
      'ai.questions.generate',
      'ai.results',
      'ai.cv.parse.dlq',
      'ai.jd.analyze.dlq',
      'ai.skills.normalize.dlq',
      'ai.match.run.dlq',
      'ai.questions.generate.dlq',
      'ai.results.dlq',
    ]);
  });
});

describe('AD-5: job payloads carry IDs only', () => {
  it('AD-5 job payloads accept the ARCHITECTURE fields', () => {
    expect(CvParseJobSchema.parse(cvJob)).toEqual(cvJob);
    expect(JdAnalyzeJobSchema.parse({ job_id: JOB_ID, jd_id: 9, jd_version: 1 })).toBeTruthy();
    expect(SkillNormalizeJobSchema.parse({ job_id: JOB_ID, skill_ids: [3, 4] })).toBeTruthy();
  });

  it('US-2.5 a SKILL_NORMALIZE job names 1 to 50 skills', () => {
    const job = (skillIds: number[]) => SkillNormalizeJobSchema.safeParse({ job_id: JOB_ID, skill_ids: skillIds });
    expect(job([]).success).toBe(false);
    expect(job(Array.from({ length: SKILL_NORMALIZE_BATCH }, (_, i) => i + 1)).success).toBe(true);
    expect(job(Array.from({ length: SKILL_NORMALIZE_BATCH + 1 }, (_, i) => i + 1)).success).toBe(false);
  });

  it('AD-5 job payloads reject extra fields, so CV or JD content cannot ride along', () => {
    expect(CvParseJobSchema.safeParse({ ...cvJob, profile: { name: 'A' } }).success).toBe(false);
    expect(JdAnalyzeJobSchema.safeParse({ job_id: JOB_ID, jd_id: 9, jd_version: 1, raw_text: 'x' }).success).toBe(
      false,
    );
  });

  it('AD-5 job_id must be a UUID', () => {
    expect(CvParseJobSchema.safeParse({ ...cvJob, job_id: '42' }).success).toBe(false);
  });

  it('US-3.2 AC-1 a MATCH job carries the pinned prompt and pairs by IDs and versions only', () => {
    expect(MatchRunJobSchema.parse(matchJob)).toEqual(matchJob);
    expect(MatchRunJobSchema.safeParse({ ...matchJob, prompt_version: null }).success).toBe(true);
    expect(MatchRunJobSchema.safeParse({ ...matchJob, pairs: [] }).success).toBe(false);
    const withProfile = { ...matchJob, pairs: [{ ...pair, profile_masked: {} }] };
    expect(MatchRunJobSchema.safeParse(withProfile).success).toBe(false);
  });
});

describe('AD-6: ai.results message', () => {
  const parse = (msg: unknown) => AiResultMessageSchema.safeParse(msg);

  it('AD-6 accepts SUCCEEDED with a result and FAILED with an error', () => {
    expect(parse(succeeded).success).toBe(true);
    expect(parse({ ...succeeded, status: 'FAILED', result: null, error: failure }).success).toBe(true);
    expect(parse({ ...succeeded, status: 'PARTIAL', error: failure }).success).toBe(true);
  });

  it('AD-6 rejects a missing job_id, an unknown status or an unknown type', () => {
    const withoutId: Partial<typeof succeeded> = { ...succeeded };
    delete withoutId.job_id;
    expect(parse(withoutId).success).toBe(false);
    expect(parse({ ...succeeded, status: 'DONE' }).success).toBe(false);
    expect(parse({ ...succeeded, type: 'ESSAY_GRADE' }).success).toBe(false);
  });

  it('AD-6 rejects a job payload of the wrong type', () => {
    expect(parse({ ...succeeded, job: { job_id: JOB_ID, jd_id: 9, jd_version: 1 } }).success).toBe(false);
  });

  it('AD-6 status, result and error must agree', () => {
    expect(parse({ ...succeeded, result: null }).success).toBe(false);
    expect(parse({ ...succeeded, error: failure }).success).toBe(false);
    expect(parse({ ...succeeded, status: 'FAILED', error: null, result: null }).success).toBe(false);
    expect(parse({ ...succeeded, status: 'FAILED', error: failure }).success).toBe(false);
    expect(parse({ ...succeeded, status: 'PARTIAL', result: null, error: failure }).success).toBe(false);
  });

  it('AD-6 the echoed job must be the same job', () => {
    const other = { ...cvJob, job_id: '0b9a8c7d-6e5f-4a3b-8c2d-1e0f9a8b7c6d' };
    expect(parse({ ...succeeded, job: other }).success).toBe(false);
  });

  it('AD-6 rejects extra fields on the message and on the result', () => {
    expect(parse({ ...succeeded, extra: 1 }).success).toBe(false);
    expect(parse({ ...succeeded, result: { ...output, score: 1 } }).success).toBe(false);
  });

  it('US-3.2 AC-9 a MATCH result comes in chunks; the last one lists the failed pairs', () => {
    expect(parse(matchResult).success).toBe(true);
    const failed = { ...pair, code: 'LLM_REFUSAL', needs_review: true };
    const last = { ...matchResult.result, final: true, items: [], failed_pairs: [failed] };
    expect(parse({ ...matchResult, status: 'PARTIAL', result: last }).success).toBe(true);
    const tooMany = Array.from({ length: MATCH_RESULT_CHUNK_MAX + 1 }, () => matchItem);
    expect(parse({ ...matchResult, result: { ...matchResult.result, items: tooMany } }).success).toBe(false);
  });

  it('US-3.2 AC-10 a MATCH item carries no total the backend could read (AD-2)', () => {
    const items = [{ ...matchItem, s_cv: 80 }];
    expect(parse({ ...matchResult, result: { ...matchResult.result, items } }).success).toBe(false);
  });
});
