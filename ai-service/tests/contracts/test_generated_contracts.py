"""AD-6: message models come from packages/shared/contracts and are never written by hand."""

import ast
import importlib
import inspect
import json
from enum import Enum
from pathlib import Path

from pydantic import BaseModel

import app
from app import contracts

APP_DIR = Path(app.__file__).parent
CONTRACTS_DIR = Path(contracts.__file__).parent
JSON_SCHEMA_DIR = APP_DIR.parent.parent / "packages" / "shared" / "contracts" / "json-schema"
HEADER = "# generated by `pnpm contracts:gen` from packages/shared/contracts - do not edit"


def contract_classes() -> set[str]:
    names: set[str] = set()
    for module_file in CONTRACTS_DIR.glob("*.py"):
        module = importlib.import_module(f"app.contracts.{module_file.stem}")
        for name, obj in inspect.getmembers(module, inspect.isclass):
            if obj.__module__ == module.__name__ and issubclass(obj, BaseModel | Enum):
                names.add(name)
    return names


def test_ad6_every_generated_file_has_the_header() -> None:
    files = sorted(CONTRACTS_DIR.glob("*.py"))
    assert files
    for file in files:
        assert file.read_text(encoding="utf-8").startswith(HEADER), file.name


def test_ad6_every_json_schema_has_a_model() -> None:
    if not JSON_SCHEMA_DIR.is_dir():  # installed without the monorepo next to it
        return
    schemas = {p.stem for p in JSON_SCHEMA_DIR.glob("*.json")}
    modules = {p.stem for p in CONTRACTS_DIR.glob("*.py")} - {"__init__"}
    assert schemas == modules
    for stem in schemas:
        title = json.loads((JSON_SCHEMA_DIR / f"{stem}.json").read_text(encoding="utf-8"))["title"]
        assert hasattr(importlib.import_module(f"app.contracts.{stem}"), title)


def test_ad6_no_contract_model_is_redefined_outside_app_contracts() -> None:
    names = contract_classes()
    assert {"CvParseJob", "CvParseResult", "AiResultMessage"} <= names
    for file in APP_DIR.rglob("*.py"):
        if CONTRACTS_DIR in file.parents:
            continue
        tree = ast.parse(file.read_text(encoding="utf-8"))
        defined = {node.name for node in ast.walk(tree) if isinstance(node, ast.ClassDef)}
        assert not defined & names, f"{file} redefines {defined & names}"


def test_ad6_queues_json_ships_with_the_package() -> None:
    manifest = json.loads((CONTRACTS_DIR / "queues.json").read_text(encoding="utf-8"))
    assert manifest["max_attempts"] == len(manifest["retry_delays_seconds"]) + 1
    assert set(manifest["jobs"]) == {"CV_PARSE", "JD_ANALYZE"}
